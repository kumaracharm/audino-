// Deterministic epoch base: 2026-11-12T18:00:00.000Z
const FIXED_BASE_TIME = 1794506400000;

function generateHistory(base: { heartRate: number; respiratoryRate: number; spo2: number; temperature: number }, count: number = 20) {
  // Use pseudo-random deterministic variation so server and client output match perfectly
  return Array.from({ length: count }, (_, i) => {
    const timestamp = new Date(FIXED_BASE_TIME - (count - i) * 5 * 60 * 1000).toISOString();
    const pseudoRand1 = ((i * 17) % 10) / 10 - 0.5;
    const pseudoRand2 = ((i * 13) % 10) / 10 - 0.5;
    const pseudoRand3 = ((i * 19) % 10) / 10 - 0.5;
    const pseudoRand4 = ((i * 23) % 10) / 10 - 0.5;

    return {
      timestamp,
      heartRate: Math.round(base.heartRate + pseudoRand1 * 6),
      respiratoryRate: Math.round(base.respiratoryRate + pseudoRand2 * 2),
      spo2: Math.round(Math.min(100, Math.max(88, base.spo2 + pseudoRand3 * 2))),
      temperature: parseFloat((base.temperature + pseudoRand4 * 0.2).toFixed(1)),
    };
  });
}

