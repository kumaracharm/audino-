// Epoch baseline
const FIXED_BASE_TIME = Date.now();

function generateInitialHistory(base: { heartRate: number; respiratoryRate: number; spo2: number; temperature: number }, count: number = 20) {
  return Array.from({ length: count }, (_, i) => {
    const timestamp = new Date(FIXED_BASE_TIME - (count - i) * 2000).toISOString();
    const pseudoRand1 = ((i * 17) % 10) / 10 - 0.5;
    const pseudoRand2 = ((i * 13) % 10) / 10 - 0.5;
    const pseudoRand3 = ((i * 19) % 10) / 10 - 0.5;
    const pseudoRand4 = ((i * 23) % 10) / 10 - 0.5;

    return {
      timestamp,
      heartRate: Math.round(base.heartRate + pseudoRand1 * 4),
      respiratoryRate: Math.round(base.respiratoryRate + pseudoRand2 * 2),
      spo2: Math.round(Math.min(100, Math.max(88, base.spo2 + pseudoRand3 * 1.5))),
      temperature: parseFloat((base.temperature + pseudoRand4 * 0.1).toFixed(1)),
    };
  });
}

