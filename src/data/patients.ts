function generateHistory(base: { heartRate: number; respiratoryRate: number; spo2: number; temperature: number }, count: number = 20) {
  const now = Date.now();
  return Array.from({ length: count }, (_, i) => ({
    timestamp: new Date(now - (count - i) * 5 * 60 * 1000).toISOString(),
    heartRate: Math.round(base.heartRate + (Math.random() - 0.5) * 8),
    respiratoryRate: Math.round(base.respiratoryRate + (Math.random() - 0.5) * 2),
    spo2: Math.round(Math.min(100, base.spo2 + (Math.random() - 0.5) * 2)),
    temperature: parseFloat((base.temperature + (Math.random() - 0.5) * 0.3).toFixed(1)),
  }));
}

